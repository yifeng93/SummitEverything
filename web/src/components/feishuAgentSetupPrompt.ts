export function buildFeishuAgentSetupPrompt(origin: string): string {
  let safeOrigin = ''
  try {
    const parsed = new URL(origin)
    safeOrigin = parsed.origin
  } catch {
    safeOrigin = '当前 SummitEverything 页面'
  }

  return `请在本机为 SummitEverything 检查并完成可安全完成的飞书接入配置。当前应用网页 origin：${safeOrigin}

这段提示词可以独立执行：助手的当前目录不一定是 SummitEverything 仓库，机器上也可能只有安装版应用。不要把当前工作目录或知识工作库目录当作源码根目录，不要硬编码用户目录，也不要因项目文档暂时找不到就停止安全配置流程。

先定位并核对这个 origin 对应的本机运行实例：
1. 将 origin 当作网页来源线索，不能默认它等同于 API origin，也不得从它猜测/替换 API 端口（例如不能把网页端口擅自改猜成 8793）。若已验证的运行配置或服务接口证实 API 使用同源地址或受支持的本机代理，可使用该已验证通道。不得拼接或输出网页 origin 的查询参数、片段、凭据或其他敏感 URL 参数。
2. 查看当前助手已连接的 SummitEverything MCP 与宿主项目配置，再按需核对实际监听该网页服务的进程及其工作目录/启动参数。只用这些有限证据交叉确认服务身份和关联工作库；不要全盘扫描。不要因机器上有多个版本就任选一个：找不到与该运行实例匹配且可验证的源码根目录时，按“源码不可用”继续。
3. 不得仅凭 cwd、目录名、知识工作库位置、端口相似或一个未验证配置来认定源码根目录。只有确认源码目录确实属于上述运行实例后，才可将仓库内文档路径相对该源码根目录解析；文档用于补充实现细节，不是普通用户继续配置的前置条件。
4. 如果当前助手运行在另一台机器，不能把此处的 localhost 当作用户原机器的 localhost。没有对原机器运行实例的本机访问能力时，不要尝试连接或改配；说明缺少的最小访问信息/动作，并可先报告当前宿主已有证据。

按以下自包含步骤继续；即使只有已安装应用、源码或文档不存在，也按可用证据安全配置，只有确实缺少能力时才停在对应步骤并说明原因：
1. 发现当前助手宿主实际支持的 MCP 配置、飞书工具/连接器和本机 CLI/技能；检查已连接的 SummitEverything MCP、飞书授权与配置，优先复用有效项。不要覆盖无关 MCP 配置，不要重复授权。
2. 当前 SummitEverything MCP 有 14 个受限工具，不提供设置或凭据写入工具，也没有 Feishu CLI bridge。MCP 连接/可读性与飞书外部授权、应用实际读取是不同验证门。只有已验证源码根目录与运行实例匹配后，才可按需阅读该目录下的 docs/handoff/FEISHU-AGENT-SETUP.md、docs/contracts/MCP-v1.md、docs/contracts/API-v1.md、README.md 中 Agent 接入说明及相关飞书接入文档/技能补充核对；缺少源码文档不改变这里写明的步骤和安全边界。
3. 在确认属于该 origin 的运行服务后，按服务实际公开且允许访问的配置能力核对非秘密设置、凭据 configured 状态和当前身份/endpoint 要求。API-v1 规定非秘密设置使用 GET/PATCH /settings、凭据使用 PUT /credentials/{provider}；调用前必须从已验证的运行配置/宿主接口证据确认 API origin、认证和适配，不能默认网页 origin 等于 API origin，也不能猜替端口/凭据路径。若证据证实同源 API 或受支持的本机代理，则使用已验证的通道。变更前读取现值，只提交必要字段并保留其它设置。不得把 CLI 可运行、配置文件存在或工具列表出现说成应用已连通。
4. 凭据只从已有钥匙串/宿主秘密管理经受支持的本机安全通道提交到应用正式凭据接口。不得将秘密输出到对话、终端、日志、提示词、仓库或普通配置；不要求用户把密钥贴到聊天；不得猜路径或生成/覆盖 token 文件。缺少安全凭据来源或受支持接口时，报告具体缺口和最小下一步。
5. 对每个要读取的 endpoint，先核实它要求的身份、scope 及目标资源归属，再与当前凭据身份和实际授予的 scope 对照；endpoint 支持且能访问目标资源时优先用应用身份，只有该 endpoint/功能明确要求 user token 时才进行对应用户授权。机器人/应用的主日历不等同于用户个人日历；不得仅凭日历可读推断读到了目标用户的日历。凭据已保存或显示 configured 只证明本机凭据存储状态，不证明授权或资源权限可用。遇到 missing_scope 时先核对缺少的 scope 和适用身份：只对确需的 user scope 请求用户授权；若缺的是 app scope，则报告需管理员开通/审批的具体权限。不得自动扩大 scope、切换身份或泛化要求 OAuth。日历是只读例外：连接完成后可直接通过应用或 MCP 刷新读取；服务端仍校验当前工作库、身份、凭据、实际 scope、明确时间范围和有界请求，且失败不自动重试。材料/任务读取与材料导入须先核实现有一次性计划及其配置、工作库、endpoint、目标资源和范围；有效计划仅在信息匹配时复用。需新计划时经应用正式流程形成待确认预览，不得代替用户确认或绕过计划。其它外部结果为 unknown 时先查看可用回执/状态，不自动重试。若官方授权需用户扫码/确认，只请求完成所需的最小动作。
6. 真实读取只有在 SummitEverything 通过受支持集成对目标 endpoint 成功读取，并有证据核对返回数据所属的目标用户/日历及请求范围时才算通过。记录实际身份、所需/已授予 scope、目标资源归属、范围、结果和计划证据。返回 0 条或成功读取机器人主日历，只能证明对应日历 endpoint 可读，不能证明用户个人日历正确；不得把这种结果报告为目标资源接入成功。无法验证资源归属、身份或 scope 时明确标为未验证，并给出最小下一步。不要创建任务、导入材料或确认正式知识。

本提示词只授权检查和配置接入，不授权真实飞书任务写入、材料导入、正式知识确认、付费模型调用、超出读取范围的真实请求或绕过身份/scope/工作库门禁。日历直接读取仅限已连接身份的有界只读调用。报告实际配置/复用内容、各验证门证据、未验证项及所需最小动作；不输出秘密或敏感 URL 参数。`
}
